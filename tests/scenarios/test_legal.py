def test_contract_review_catches_all_seven_planted_issues():
    out = call("contract-reviewer", "detect_clauses", contract_text=SAAS_CONTRACT, my_role="customer", my_jurisdiction="Oregon")
    flags = " | ".join(flags_of(out))
    missed = [issue for issue, proof in CONTRACT_PLANTED.items() if proof not in flags]
    assert missed == [], f"planted issues missed: {missed}"
    assert "perpetual, irrevocable licence to your data" in flags  # the data problem is also quoted
    assert out["liability_cap"]["capped_party"] == "vendor" and out["liability_cap"]["months_of_fees"] == 1
    assert out["governing_law"] == "Florida" and "Miami-Dade" in out["venue"]
    assert out["risk_score"] >= 50 and out["verdict"].startswith("Do not sign")
    # regressions: "limited liability company" is not a liability cap; "revenues" is not a venue clause
    clauses = {c["key"]: c["excerpt"] for c in out["clauses_found"]}
    assert "limited liability company" not in clauses["limitation_of_liability"]
    assert "Florida" in clauses["governing_law"] or "governed by" in clauses["governing_law"]


