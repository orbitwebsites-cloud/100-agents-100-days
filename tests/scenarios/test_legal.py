def test_contract_dates_match_hand_calculation():
    eff = date(2026, 10, 31)
    end = last_day_of_term(eff, 12)
    notice = end - timedelta(days=90)
    assert (end, notice) == (date(2027, 10, 30), date(2027, 8, 1)) and notice.weekday() == 6  # a Sunday
    dl = call("contract-reviewer", "extract_deadlines", contract_text=SAAS_CONTRACT, effective_date="2026-10-31")
    assert dl["initial_term_ends"] == end.isoformat()
    ninety = next(d for d in dl["durations"] if d["days"] == 90)
    assert ninety["counts_from"] == "before end of term" and ninety["from_effective_date"] is None
    assert ninety["deadline_in_initial_term"] == notice.isoformat()
    survival = next(d for d in dl["durations"] if d["duration"] == "3 years")
    assert survival["type"] == "confidentiality / survival"  # not a 1,095-day "notice period"
    assert dl["longest_notice_days"] == 90
    for d in dl["durations"]:  # event-anchored durations are never shown as effective-date dates
        if d["counts_from"] in ("from notice", "from invoice date", "after termination / expiry"):
            assert d["from_effective_date"] is None
    cal = call("contract-reviewer", "renewal_calendar", effective_date="2026-10-31", initial_term_months=12, notice_days=90)
    assert cal["initial_term_end"].startswith("2027-10-30") and cal["notice_deadline"].startswith("2027-08-01")
    assert cal["reminder_date"].startswith((notice - timedelta(days=30)).isoformat())
    assert friday_before(notice).isoformat() in cal["weekend_note"]  # 2027-07-30
    r1 = cal["renewal_cycles"][0]
    assert (r1["starts"], r1["ends"], r1["notice_deadline"]) == ("2027-10-31", last_day_of_term(date(2027, 10, 31), 12).isoformat(), "2028-08-01")


