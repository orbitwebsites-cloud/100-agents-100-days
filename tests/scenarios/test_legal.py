def reference_mtdc(subaward_allowance: float) -> tuple[float, float]:
    """Hand MTDC per 2 CFR 200.1: salaries + fringe + travel + supplies (incl. sub-threshold laptops) + services + first $X of the subaward."""
    salaries = 70000 * 0.25 * 2 + 52000 * 0.5 * 2
    fringe = salaries * 0.30
    direct = salaries + fringe + 6 * 1200 + 18000 + 4 * 1800 + 6500 + 40 * 250 + 15000 + 60000
    mtdc = salaries + fringe + 6 * 1200 + 4 * 1800 + 6500 + 15000 + min(60000, subaward_allowance)
    return direct, mtdc


def test_grant_budget_mtdc_2024_rules():
    direct, mtdc = reference_mtdc(50_000)
    out = call("grant-writer", "budget_table", line_items=GRANT_LINES, fringe_rate_pct=30, indirect_rate_pct=15, indirect_base="mtdc", request_cap=250_000)
    assert (out["total_direct"], out["mtdc"]) == (direct, mtdc) == (237_000, 199_000)
    assert out["indirect"] == mtdc * 0.15 == 29_850 and out["total_request"] == 266_850
    assert out["mtdc_exclusions"] == {"equipment": 18_000, "participant_support": 10_000, "subaward amounts above $50,000 each": 10_000}
    assert any("Laptops" in f and "supplies" in f for f in out["flags"])  # $1,800/unit < $10,000
    over = next(f for f in out["flags"] if "exceeds the $250,000 cap" in f)
    assert f"${(266_850 - 250_000) / 1.15:,.0f}" in over  # $14,652 of MTDC-eligible cuts, not $16,850


