def add_months(d: date, months: int) -> date:
    y, m = divmod(d.month - 1 + months, 12)
    y += d.year
    return date(y, m + 1, min(d.day, calendar.monthrange(y, m + 1)[1]))


def last_day_of_term(start: date, months: int) -> date:
    """A 12-month term from 2026-10-31 runs through 2027-10-30 (the day before the anniversary)."""
    anniversary = add_months(start, months)
    return anniversary if anniversary.day != start.day else anniversary - timedelta(days=1)


def friday_before(d: date) -> date:
    return d - timedelta(days=d.weekday() - 4) if d.weekday() >= 5 else d


def call(slug: str, tool: str, **kwargs):
    out = registry.get(slug).get_tool(tool).call(kwargs)
    assert "not legal" in out.get("scope_note", "").lower(), f"{slug}.{tool} output lacks the not-legal-advice scope note"
    return out


def flags_of(out: dict) -> list[str]:
    return [f["flag"] for f in out["red_flags"]]


